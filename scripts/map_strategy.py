#!/usr/bin/env python3
"""Generate per-map strategy documents for all 70 published maps.

Inputs:
- bots/Chamero/maps/maps.json            map facts (gems, camps, altars, class)
- matches/top20-scout/census.json        top-20 team-game features per map
- matches/map-campaign-v22-20261028/     our v22 results vs real teams
- matches/chamero-analysis.json          Chamero v25-v30 results (top-5 panel)

Output: docs/maps/<map>.md + docs/MAP_STRATEGY.md index.

Recommendations are labelled: [measured] from downloaded data, [derived] from
map facts, [hypothesis] proposal. Nothing here is validated gameplay.
"""
import json
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAPS = ROOT / "bots" / "Chamero" / "maps" / "maps.json"
CENSUS = ROOT / "matches" / "top20-scout" / "census.json"
OURS = ROOT / "matches" / "map-campaign-v22-20261028" / "results"
CHAM = ROOT / "matches" / "chamero-analysis.json"
OUTD = ROOT / "docs" / "maps" / "strategy"
INDEX = ROOT / "docs" / "MAP_STRATEGY.md"

def load(p):
    return json.loads(Path(p).read_text(encoding="utf-8-sig"))

def mean(xs):
    xs = [x for x in xs if x is not None]
    return sum(xs) / len(xs) if xs else None

def fmt(v, d=1):
    return f"{v:.{d}f}" if v is not None else "n/a"

# Recommended stat per champion for items (from top-20 emblem analysis)
MAINSTAT = {
    "Vesper Vale": "Strength", "Marcella": "Focus", "Vendetta": "Strength",
    "Heart of Ruin": "Focus", "Ryth": "Health", "Tavi": "Strength",
    "Willow": "Strength", "Varg": "Strength", "Prism": "Health",
    "Cassi": "Focus", "Issac": "Strength", "Ren": "Health", "Stellar": "Focus",
}
CARRY = {"Vesper Vale", "Marcella", "Prism", "Varg"}
SUPPORT = {"Ryth", "Willow", "Tavi", "Ren", "Heart of Ruin"}

def norm(n):
    """maps.json uses dashes, match data uses underscores."""
    return n.replace("-", "_") if n else n

def main():
    maps = {norm(m["map"]): m for m in load(MAPS)}
    census = load(CENSUS)
    games = census["games_detail"]
    by_map = defaultdict(list)
    for g in games:
        if g["map"]:
            by_map[norm(g["map"])].append(g)

    ours = defaultdict(list)
    for f in sorted(OURS.glob("b*.json")):
        for m in load(f)["matches"]:
            ours[norm(m["map"])].append(m)
    cham = defaultdict(list)
    if CHAM.exists():
        for r in load(CHAM):
            cham[norm(r["map"])].append(r)

    OUTD.mkdir(parents=True, exist_ok=True)
    index = ["# Per-map strategy guide", "",
             "One document per published map. Each combines map facts, what "
             "winning top-20 teams did on that map, our recorded results, and a "
             "concrete draft/camp/item/traversal plan. Generated by "
             "`scripts/map_strategy.py`.", "",
             "Labels: **[measured]** = observed in downloaded match data, "
             "**[derived]** = computed from map facts, **[hypothesis]** = "
             "proposal, not validated.", "",
             "| Map | Class | Picks | Gems | Altars | Our record |", "",
             "| --- | --- | --- | --- | --- | --- |"]
    index[6] = ""  # fix header rows
    index[6:8] = ["| Map | Class | Picks | Gems | Altars | Our record |",
                  "| --- | --- | ---: | ---: | ---: | --- |"]

    for name in sorted(maps):
        f = maps[name]
        gs = by_map.get(name, [])
        wins = [g for g in gs if g["won"]]
        cls = f["class"]
        L = [f"# {name} strategy", ""]
        L.append(f"**Class:** {cls} | **Size:** {f['size']} | **Picks:** {f['picks']} | "
                 f"**Altars:** {f['altars']} | **Camp groups:** {f['groups']}")
        L.append("")
        L.append("## Map facts [derived]")
        L.append("")
        L.append(f"- Gems {f['gems']} ({f['gems_per_champ']}/champ), gold {f['gold']} "
                 f"({f['gold_per_champ']}/champ), camp HP per gem {f['hp_per_gem']}.")
        L.append(f"- Gem concentration: top {f['top']:.0%}, center {f['center']:.0%}, "
                 f"monolith-held {f['mono']:.0%}, harmless camps {f['harmless']:.0%}.")
        L.append(f"- Camp density {f['density']}; brawl flag: {f['brawl']}.")
        L.append("")

        # top-20 behaviour on this map
        L.append("## What top-20 teams did here [measured]")
        L.append("")
        if gs:
            wd = Counter(tuple(sorted(g["draft"])) for g in wins)
            wd_all = Counter(tuple(sorted(g["draft"])) for g in gs)
            chw = Counter(c for g in wins for c in g["draft"])
            fams = Counter()
            cons = Counter()
            for g in wins:
                fams.update(g.get("item_families", {}))
                cons.update(g.get("consumables", {}))
            L.append(f"- Sample: {len(gs)} team-games, {len(wins)} wins.")
            if wd:
                top = wd.most_common(3)
                L.append("- Winning drafts: " + "; ".join(
                    f"{', '.join(d)} ({c}w)" for d, c in top))
            if chw:
                L.append("- Champions in winning drafts: " + ", ".join(
                    f"{n} ({c}w)" for n, c in chw.most_common(8)))
            L.append(f"- Winners: kills {fmt(mean([g['kills'] for g in wins]))}, "
                     f"deaths {fmt(mean([g['deaths'] for g in wins]))}, "
                     f"tribute {fmt(mean([g['tribute_mean'] for g in wins]))} gems, "
                     f"wards {fmt(mean([g['wards'] for g in wins]), 0)}, "
                     f"farm spread {fmt(mean([g['farm_spread'] for g in wins]))} tiles.")
            if fams:
                L.append("- Winner item families: " + ", ".join(
                    f"{k}×{v}" for k, v in fams.most_common(6)))
            if cons:
                L.append("- Winner consumables: " + ", ".join(
                    f"{k}×{v}" for k, v in cons.most_common()))
        else:
            L.append("- No top-20 games downloaded for this map; plan is "
                     "derived from map facts and class-level behaviour.")
        L.append("")

        # our record
        L.append("## Our record here [measured]")
        L.append("")
        om = ours.get(name, [])
        cm = cham.get(name, [])
        if om:
            w = sum(1 for m in om if m["result"] == "win")
            L.append(f"- v22 campaign vs five ~peer teams: {w}/{len(om)} wins "
                     f"(results/b*.json).")
        if cm:
            w = sum(1 for r in cm if r["won"])
            L.append(f"- Chamero vs top-5: {w}/{len(cm)} wins "
                     f"(avg {fmt(mean([r['score_us'] for r in cm]),0)}-"
                     f"{fmt(mean([r['score_them'] for r in cm]),0)}).")
        if not om and not cm:
            L.append("- No recorded online results for our bots on this map.")
        L.append("")

        # ---- recommendations ----
        L.append("## Recommended plan")
        L.append("")

        # draft
        L.append("### Draft")
        L.append("")
        pick_n = f["picks"]
        core = ["Vesper Vale", "Vendetta", "Heart of Ruin", "Marcella"]
        if wins and wd:
            best = list(wd.most_common(1)[0][0])
            L.append(f"- Primary: copy the most-frequent winning draft here — "
                     f"**{', '.join(best)}** [measured].")
        if cls == "jackpot" or f["brawl"]:
            fifth = ["Ryth"]
            if pick_n >= 5: fifth = ["Ryth", "Cassi & Issac"][:pick_n-4]
            rec = (core + fifth)[:pick_n]
            L.append(f"- Fallback: **{', '.join(rec)}** — melee-heavy "
                     f"deathball for the contested objective [hypothesis]. "
                     f"Ryth's AoE stun + bodies for trades; drop Willow/Tavi.")
        elif cls == "boss":
            rec = (core + ["Ryth", "Tavi"])[:pick_n]
            L.append(f"- Fallback: **{', '.join(rec)}** — sustain clear comp "
                     f"for long monolith sieges [hypothesis].")
        elif cls in ("rich", "normal"):
            rec = (core + ["Tavi", "Ryth"])[:pick_n]
            L.append(f"- Fallback: **{', '.join(rec)}** — fast clear + "
                     f"one banker [hypothesis].")
        else:  # sparse
            rec = (core + ["Tavi"])[:pick_n]
            L.append(f"- Fallback: **{', '.join(rec)}** — low-economy map; "
                     f"carry + efficient clearers, skip Willow [hypothesis].")
        L.append("")

        # camps
        L.append("### Camp targets")
        L.append("")
        if cls == "jackpot":
            L.append(f"- One group holds ~{max(f['top'],f['center'],f['mono']):.0%} of "
                     f"the map's {f['gems']} gems [derived]. That group IS the map: "
                     f"send the whole team at round 0, clear it together, escort "
                     f"the carrier to the altar. Conceding it = conceding the game "
                     f"(our the_line record: 0 points in 25 straight games [measured]).")
            L.append("- After the jackpot, farm outward in a cluster — do not "
                     "spread solo while enemies are alive [hypothesis].")
        elif cls == "boss":
            L.append(f"- Monoliths hold {f['mono']:.0%} of gems [derived]. Prioritize "
                     f"the nearest monolith camps; use sustained chipping "
                     f"(camps keep damage between visits) + death-blacklist so a "
                     f"killed champ does not immediately re-die to the same camp.")
            L.append("- Do NOT hold gems for a group gate assault vs real teams — "
                     "bank through open altars early; break gate camps around "
                     "round 400-700 like top teams, not 900+ [measured].")
        elif cls == "sparse":
            L.append(f"- Only {f['gems_per_champ']} gems/champ [derived]. Take "
                     f"high-value camps within ~15 tiles of spawn; skip far "
                     f"low-value trips (travel dominates on sparse maps).")
        else:
            L.append(f"- {f['gems_per_champ']} gems/champ across {f['groups']} groups "
                     f"[derived]. Spread-farm: each champ claims a camp cluster, "
                     f"top teams' farm spread here was "
                     f"{fmt(mean([g['farm_spread'] for g in wins or gs]))} tiles.")
        if f["center"] >= 0.4:
            L.append(f"- {f['center']:.0%} of gems are in the center [derived] — "
                     f"contest it early; this is the 'central gems' failure we "
                     f"observed (our bot walked past center gems to side camps).")
        if f["top"] >= 0.5:
            L.append(f"- {f['top']:.0%} of gems sit in one top region [derived] — "
                     f"treat it as the jackpot objective even if the map is "
                     f"otherwise spread out.")
        if f["mono"] >= 0.25 and f["altars"] <= 2:
            L.append(f"- **Gated altar warning**: {f['mono']:.0%} of gems are "
                     f"monolith-held and only {f['altars']} altar(s) exist "
                     f"[derived]. Do NOT hold gems waiting for a group gate "
                     f"assault — bank through open altars early; if all altars "
                     f"are gated, break the gate around round 400-700 like top "
                     f"teams (not 900+), then tribute 200+ at once [measured].")
        if f["harmless"] >= 0.4:
            L.append(f"- {f['harmless']:.0%} of camps are harmless [derived] — "
                     f"free farming; take them first while the enemy fights "
                     f"dangerous camps.")
        L.append("")

        # items
        L.append("### Items / shards / emblems")
        L.append("")
        L.append("- Opening (everyone): Monster + Jungle Health for early clear "
                 "and sustain — matches every top-20 opening [measured].")
        for ch in (rec if 'rec' in dir() else core):
            st = MAINSTAT.get(ch, "Strength")
            role = "carry" if ch in CARRY else "support"
            L.append(f"- {ch} ({role}): Bruiser {st} shards/emblems as main stack; "
                     f"{'add Power ' + st + ' once Bruiser caps' if role=='carry' else 'Durability Health for tankiness'}.")
        if cls == "jackpot":
            L.append("- Buy a **Tribute** emblem for the designated carrier — "
                     "bigger banked hauls decide jackpot maps [hypothesis].")
        L.append("- Consumables: Altar Lock on the altar nearest our farm "
                 f"(top teams averaged {fmt(mean([sum(g['consumables'].values()) for g in wins or gs]),1)} "
                 f"consumables/game here); TP crystal(s) "
                 f"{'REQUIRED — this map has terrain-separated camps' if cls in ('rich',) and f['altars']>=4 else 'for carrier escapes'}.")
        L.append("")

        # traversal
        L.append("### Traversal / positioning")
        L.append("")
        if cls == "jackpot" or f["brawl"]:
            L.append("- Move as one group; nobody farms alone beyond ~6 tiles "
                     "from the nearest ally. Escort carriers to the altar; "
                     "fight only with 3+ bodies present.")
        elif cls == "boss":
            L.append("- Two loose pairs beat one ball here: one pair sieges "
                     "monoliths, one pair farms side camps + banks. Regroup "
                     "within ~12 tiles when enemies appear.")
        else:
            L.append("- Wide spread (one champ per camp cluster, matching the "
                     "measured winner spread above), regroup on enemy sighting "
                     "within ~12 tiles.")
        L.append(f"- Bank at the nearest of {f['altars']} altars; tribute when a "
                 f"carrier holds ~{fmt(max(20, mean([g['tribute_mean'] for g in wins]) or 35),0)} "
                 f"gems or when an enemy is chasing — losing carried gems is the "
                 f"main way games here are lost.")
        L.append("")
        L.append("---")
        L.append("*Unvalidated plan derived from data; test locally before adopting.*")

        (OUTD / f"{name}.md").write_text("\n".join(L), encoding="utf-8")
        rec_s = "-"
        if om:
            w = sum(1 for m in om if m["result"] == "win")
            rec_s = f"v22 {w}/{len(om)}"
        if cm:
            w = sum(1 for r in cm if r["won"])
            rec_s += f" | Chamero {w}/{len(cm)}"
        index.append(f"| [{name}](maps/strategy/{name}.md) | {cls} | {f['picks']} | "
                     f"{f['gems']} | {f['altars']} | {rec_s} |")

    INDEX.write_text("\n".join(index) + "\n", encoding="utf-8")
    print(f"wrote {len(maps)} map docs + index")

if __name__ == "__main__":
    main()
